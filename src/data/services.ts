export function getService(slug: string) {
  return services.find((s) => s.slug === slug);
}

export function getServices(slugs: string[]) {
  return slugs.map(getService).filter((s): s is Service => Boolean(s));
}

export function serviceHref(slug: string, anchor?: string) {
  return `/services/${slug}${anchor ? `#${anchor}` : ""}`;
}

export const featuredServices = services.filter((s) => s.featured);
export const additionalServices = services.filter((s) => !s.featured);
